export interface Broadcast {
  id: string;
  headline: string;
  detail: string;
  sentiment: -1 | 0 | 1;  // -1 bear, 0 neutral, +1 bull
  tokens: string[];         // tokens most affected
  category: 'bull' | 'bear' | 'fud' | 'hopium' | 'airdrop' | 'regulation' | 'tech' | 'macro';
  timestamp: number;
}

